#!/usr/bin/env python3
"""Build the score ring + 4K label overlay images and the Kometa overlay file that uses them.

    pip install pillow
    python3 tools/build_overlays.py            # writes overlays/images/ and overlays/score_ring_4k.yml

Design (all sizes are pixels on Kometa's 1000x1500 poster canvas):
  * 4K label, top-left, 44px in: #282a2d fill, white text, 6px #3e44ff outline, 92px tall, radius 20.
  * Score ring, bottom-right (44px from the right, 56px from the bottom so Plex's progress bar stays clear):
    180px dark disc; the arc's length is the score and its colour the band; the unfilled part is a dark
    tint of the same colour; the score in the middle as a whole number out of 100.
  * Bands: 0-34 deep red, 35-49 coral, 50-64 yellow, 65-79 lime, 80+ emerald.

The score is MDBList's average (Kometa: mass_metadata_update ratings user: mdb_average), which Kometa stores
in Plex's user rating field as 0-10. Each ring overlay matches one tenth of that range with a plex_search,
so the ring for 7.8 shows "78". No ring for fewer than MIN_TMDB_VOTES TMDb votes, a score of 0 (no data) or
100 (treated as too few votes).

Everything is drawn at 4x and box-downsampled, so edges are clean without resampling halos.
"""
import argparse
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "fonts" / "Figtree[wght].ttf"   # SIL Open Font License; a close match to Avenir Next Bold
FONT_WEIGHT = 739                              # weight-matched to Avenir Next Bold's stroke density
K = 4                                          # supersampling factor

# label
LABEL_TEXT, LABEL_SIZE, LABEL_H, LABEL_PAD, LABEL_RADIUS, LABEL_LINE = "4K", 54, 92, 30, 20, 6
LABEL_FILL, LABEL_FG, LABEL_OUTLINE = (40, 42, 45, 255), (255, 255, 255, 255), (62, 68, 255, 255)
OFFSET = 44
# ring
D, STROKE, INSET, NUM_SIZE = 180, 18, 15, 66
DISC = (21, 23, 27, 255)
RING_RIGHT, RING_BOTTOM = 44, 56
BANDS = [(80, (16, 206, 112)), (65, (150, 214, 86)), (50, (247, 198, 62)), (35, (255, 128, 86)), (0, (236, 40, 58))]
TRACK_TINT = 0.30
MIN_TMDB_VOTES = 20


def font(size):
    f = ImageFont.truetype(str(FONT), int(size * K))
    try:
        f.set_variation_by_axes([FONT_WEIGHT if a["name"] in (b"Weight", "Weight") else a["default"] for a in f.get_variation_axes()])
    except OSError:
        pass  # a static (non-variable) font file
    return f


def text_box(text, size):
    l, t, r, b = font(size).getbbox(text)
    return (r - l) / K, (b - t) / K, l / K, t / K


def draw_text(d, x, y, text, size, fill):
    """Draw text with its ink's top-left corner at (x, y)."""
    _, _, l, t = text_box(text, size)
    d.text(((x - l) * K, (y - t) * K), text, font=font(size), fill=fill)


def band_colour(score):
    return next(col for floor, col in BANDS if score >= floor)


def mix(a, b, t):
    return tuple(int(x * (1 - t) + y * t) for x, y in zip(a[:3], b[:3])) + (255,)


def label_image(text=LABEL_TEXT, outline=LABEL_OUTLINE):
    tw, th, _, _ = text_box(text, LABEL_SIZE)
    w = max(tw + 2 * LABEL_PAD, 110)
    im = Image.new("RGBA", (int(w * K), int(LABEL_H * K)), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle([0, 0, w * K - 1, LABEL_H * K - 1], radius=LABEL_RADIUS * K, fill=LABEL_FILL, outline=outline, width=LABEL_LINE * K)
    draw_text(d, (w - tw) / 2, (LABEL_H - th) / 2, text, LABEL_SIZE, LABEL_FG)
    return im.reduce(K)


def ring_image(score):
    im = Image.new("RGBA", (D * K, D * K), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    c = D / 2
    d.ellipse([0, 0, D * K, D * K], fill=DISC)
    col = band_colour(score) + (255,)
    rr = c - INSET
    box = [(c - rr) * K, (c - rr) * K, (c + rr) * K, (c + rr) * K]
    d.arc(box, 0, 360, fill=mix(DISC, col, TRACK_TINT), width=STROKE * K)
    end = -90 + 360 * score / 100
    d.arc(box, -90, end, fill=col, width=STROKE * K)
    rm = rr - STROKE / 2
    for ang in (-90, end):  # round caps
        a = math.radians(ang)
        px, py = c + rm * math.cos(a), c + rm * math.sin(a)
        d.ellipse([(px - STROKE / 2) * K, (py - STROKE / 2) * K, (px + STROKE / 2) * K, (py + STROKE / 2) * K], fill=col)
    label = str(score)
    tw, th, _, _ = text_box(label, NUM_SIZE)
    draw_text(d, c - tw / 2, c - th / 2, label, NUM_SIZE, (255, 255, 255, 255))
    return im.reduce(K)


def overlay_yaml(image_root="config/overlay-images"):
    lines = [
        "# Score ring (bottom-right) + 4K label (top-left). Generated by tools/build_overlays.py - edit that, not this file.",
        "# Score: MDBList's average, stored by Kometa in Plex's user rating field (0-10) and shown here out of 100.",
        f"# No ring for: no score, fewer than {MIN_TMDB_VOTES} TMDb votes, or a perfect 100 (treated as too few votes).",
        "overlays:",
        "  4K Label:",
        "    overlay:",
        "      name: 4K Label",
        f"      file: {image_root}/labels/4k.png",
        "      horizontal_align: left",
        "      vertical_align: top",
        f"      horizontal_offset: {OFFSET}",
        f"      vertical_offset: {OFFSET}",
        "    plex_all: true",
    ]
    for score in range(1, 100):
        lines += [
            f"  Score {score}:",
            "    overlay:",
            f"      name: Score {score}",
            f"      file: {image_root}/ring/r{score:02d}.png",
            "      horizontal_align: right",
            "      vertical_align: bottom",
            f"      horizontal_offset: {RING_RIGHT}",
            f"      vertical_offset: {RING_BOTTOM}",
            "      group: score",
            "      weight: 10",
            "    ignore_blank_results: true      # empty score bands are normal; warn instead of error",
            "    plex_search:",
            "      all:",
            f"        user_rating.gte: {score / 10 - 0.05:.2f}",
            f"        user_rating.lt: {score / 10 + 0.05:.2f}",
            "    filters:",
            f"      tmdb_vote_count.gte: {MIN_TMDB_VOTES}",
        ]
    return "\n".join(lines) + "\n"


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--out", default=str(ROOT / "overlays"), help="output folder (default: overlays/)")
    args = p.parse_args()
    out = Path(args.out)
    (out / "images" / "ring").mkdir(parents=True, exist_ok=True)
    (out / "images" / "labels").mkdir(parents=True, exist_ok=True)
    for old in (out / "images" / "ring").glob("r*.png"):
        old.unlink()
    for score in range(1, 100):
        ring_image(score).save(out / "images" / "ring" / f"r{score:02d}.png", optimize=True)
    label_image().save(out / "images" / "labels" / "4k.png", optimize=True)
    (out / "score_ring_4k.yml").write_text(overlay_yaml())
    print(f"wrote 99 rings, the 4K label and {out / 'score_ring_4k.yml'}")


if __name__ == "__main__":
    main()
